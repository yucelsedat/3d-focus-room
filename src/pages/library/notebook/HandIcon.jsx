// Ekrandaki çizgi kalınlığı (px); yazı fontunun çizgisiyle aynı
const STROKE_PX = 2.2

// Düğme olmadan yalnızca çizim (ör. boş ekranlardaki süs)
export function HandDrawing({ shape, size = 32, stroke = STROKE_PX, color = notebook.graphite, fill = 'none' }) {
  return (
    <svg width={size} height={size} viewBox="0 0 40 40" aria-hidden="true" style={{ display: 'block' }}>
      <g
        fill={fill}
        stroke={color}
        strokeWidth={(stroke * 40) / size}
        strokeLinecap="round"
        strokeLinejoin="round"
        opacity={0.92}
      >
        {SHAPES[shape].map((d) => (
          <path key={d} d={d} />
        ))}
      </g>
    </svg>
  )
}

